import java.sql.Connection;
import java.sql.Date;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Scanner;

// Console app that connects to PostgreSQL with JDBC and does CRUD operations on the students table.
public class StudentApp {

    // Database credentials
    private static final String URL = "jdbc:postgresql://localhost:5432/students_db";
    private static final String USER = "postgres";
    private static final String PASSWORD = "postgres";

    // PostgreSQL error codes for the table's constraints
    private static final String UNIQUE_VIOLATION = "23505";
    private static final String NOT_NULL_VIOLATION = "23502";

    private static Connection getConnection() throws SQLException {
        return DriverManager.getConnection(URL, USER, PASSWORD);
    }

    // Retrieves and displays all records from the students table
    public static void getAllStudents() {
        String sql = "SELECT student_id, first_name, last_name, email, enrollment_date "
                   + "FROM students ORDER BY student_id";

        try (Connection conn = getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(sql)) {

            String format = "%-11s %-12s %-12s %-28s %-15s%n";
            System.out.printf(format, "student_id", "first_name", "last_name", "email", "enrollment_date");
            System.out.println("-".repeat(80));

            int count = 0;
            while (rs.next()) {
                Date enrolled = rs.getDate("enrollment_date");
                System.out.printf(format,
                        rs.getInt("student_id"),
                        rs.getString("first_name"),
                        rs.getString("last_name"),
                        rs.getString("email"),
                        enrolled == null ? "" : enrolled.toString());
                count++;
            }

            if (count == 0) {
                System.out.println("No students found.");
            } else {
                System.out.println("(" + count + " row" + (count == 1 ? "" : "s") + ")");
            }
        } catch (SQLException e) {
            printSqlError("Could not retrieve students", e);
        }
    }

    // Inserts a new student into the table. student_id is serially generated by the db
    public static void addStudent(String firstName, String lastName, String email, String enrollmentDate) {
        // enrollment_date can be left blank, but if supplied we enforce YYYY-MM-DD
        Date date = null;
        if (enrollmentDate != null) {
            try {
                date = Date.valueOf(enrollmentDate);
            } catch (IllegalArgumentException e) {
                System.out.println("Invalid date '" + enrollmentDate + "'. Use the format YYYY-MM-DD.");
                return;
            }
        }

        String sql = "INSERT INTO students (first_name, last_name, email, enrollment_date) "
                   + "VALUES (?, ?, ?, ?) RETURNING student_id";

        try (Connection conn = getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setString(1, firstName);
            pstmt.setString(2, lastName);
            pstmt.setString(3, email);
            pstmt.setDate(4, date);

            try (ResultSet rs = pstmt.executeQuery()) {
                if (rs.next()) {
                    System.out.println("Student added successfully with student_id " + rs.getInt("student_id") + ".");
                }
            }
        } catch (SQLException e) {
            printSqlError("Could not add student", e);
        }
    }

    // Updates the email of the student with the given id
    public static void updateStudentEmail(int studentId, String newEmail) {
        String sql = "UPDATE students SET email = ? WHERE student_id = ?";

        try (Connection conn = getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setString(1, newEmail);
            pstmt.setInt(2, studentId);

            int rowsUpdated = pstmt.executeUpdate();
            if (rowsUpdated > 0) {
                System.out.println("Email for student " + studentId + " updated to " + newEmail + ".");
            } else {
                System.out.println("No student with student_id " + studentId + " was found.");
            }
        } catch (SQLException e) {
            printSqlError("Could not update email", e);
        }
    }

    // Deletes the student with the given id
    public static void deleteStudent(int studentId) {
        String sql = "DELETE FROM students WHERE student_id = ?";

        try (Connection conn = getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setInt(1, studentId);

            int rowsDeleted = pstmt.executeUpdate();
            if (rowsDeleted > 0) {
                System.out.println("Student " + studentId + " deleted successfully.");
            } else {
                System.out.println("No student with student_id " + studentId + " was found.");
            }
        } catch (SQLException e) {
            printSqlError("Could not delete student", e);
        }
    }

    // Prints re-usable readable error messages
    private static void printSqlError(String action, SQLException e) {
        if (UNIQUE_VIOLATION.equals(e.getSQLState())) {
            System.out.println(action + ": that email is already used by another student (email must be unique).");
        } else if (NOT_NULL_VIOLATION.equals(e.getSQLState())) {
            System.out.println(action + ": first name, last name and email are required (NOT NULL).");
        } else {
            System.out.println(action + ": " + e.getMessage());
        }
    }

    // Checks the db connection, then shows a menu to call each function for easy demo
    public static void main(String[] args) {
        try (Connection conn = getConnection()) {
            System.out.println("Connected to PostgreSQL successfully!");
        } catch (SQLException e) {
            System.out.println("Failed to establish connection: " + e.getMessage());
            return;
        }

        Scanner in = new Scanner(System.in);
        while (true) {
            System.out.println();
            System.out.println("===== Student Database =====");
            System.out.println("1. getAllStudents()");
            System.out.println("2. addStudent(first_name, last_name, email, enrollment_date)");
            System.out.println("3. updateStudentEmail(student_id, new_email)");
            System.out.println("4. deleteStudent(student_id)");
            System.out.println("0. Exit");
            System.out.print("Choose an option: ");
            if (!in.hasNextLine()) return;
            String choice = in.nextLine().trim();

            switch (choice) {
                case "1" -> getAllStudents();
                case "2" -> addStudent(prompt(in, "First name"), prompt(in, "Last name"),
                                       prompt(in, "Email"), prompt(in, "Enrollment date (YYYY-MM-DD)"));
                case "3" -> {
                    Integer id = promptInt(in, "Student id");
                    if (id != null) updateStudentEmail(id, prompt(in, "New email"));
                }
                case "4" -> {
                    Integer id = promptInt(in, "Student id");
                    if (id != null) deleteStudent(id);
                }
                case "0" -> {
                    System.out.println("Goodbye.");
                    return;
                }
                default -> System.out.println("Please enter 0-4.");
            }
        }
    }

    // Reads a line of input; blank input becomes null so the NOT NULL constraints apply
    private static String prompt(Scanner in, String label) {
        System.out.print(label + ": ");
        if (!in.hasNextLine()) return null;
        String text = in.nextLine().trim();
        return text.isEmpty() ? null : text;
    }

    // Reads a student id, returns null if it isn't a number
    private static Integer promptInt(Scanner in, String label) {
        String text = prompt(in, label);
        if (text == null) {
            System.out.println("A student id is required.");
            return null;
        }
        try {
            return Integer.parseInt(text);
        } catch (NumberFormatException e) {
            System.out.println("'" + text + "' is not a valid number.");
            return null;
        }
    }
}
